r"""Error-limit and confidence ablation of TERA's certificate: tables/alpha_delta_body.tex (Sumanth, 2026-11-13).

Source: the analysis follower's alpha / delta grid in matrix_rows.jsonl (score_matrix.py), the same hash-pinned file
Table 3 reads. Cells g{aa}{dd}_c6c_* are the two-sided certificate (A-1d, both sides tested at delta) of each run at
alpha_s = alpha_f = 0.aa and delta = 0.dd; g0505_c6c_* must equal the c6c_* behind Table 3, run by run (asserted).
Runs: TERA (matrix_role 'method', U at rho = 0.75), six settings, three seeds. Rows: (alpha, delta) in
{(0.05, 0.05), (0.05, 0.01), (0.01, 0.05), (0.01, 0.01)}; the first is the paper's setting.

Entries follow the tables' rules (make_tables.value): means over seeds in percent, recall and abstention over all three
seeds, errors over the seeds with a nonempty predicted class with a superscript count below three, and -- for an
outcome no seed predicts (its recall too). No shading: the rows hold different error limits. A dagger on Abst. marks a
cell where, in every seed, D_cal holds fewer calibration states of an outcome than the minimum count the test needs at
these limits (g*_lim6c), so no threshold setting can pass. Layout as make_tables (Option A).

    make_alpha_delta_table.py [--paper]   -> tables/alpha_delta_body.tex, values/table_alpha_delta_values.json
"""
import argparse, hashlib, json, shutil
from pathlib import Path
import make_tables as T
from common import ASSETS, VALUES, PAPER_TABLES

NAME = 'alpha_delta'
WRAPPED_IN = 'sections/appendix_thresholds.tex'
GRID = [('g0505', '0.05', '0.05'), ('g0501', '0.05', '0.01'), ('g0105', '0.01', '0.05'), ('g0101', '0.01', '0.01')]
FIELDS = [('rec', 'c6c_rec'), ('fdr', 'c6c_fp'), ('fail_rec', 'c6c_fail_rec'), ('for', 'c6c_ferr'), ('abstain', 'c6c_abstain')]


def label(a, d):
    return rf'$\alpha={a}$, $\delta={d}$'


def main(paper):
    meta = json.loads((ASSETS / 'generalized_6c_values.json').read_text())
    source = Path(meta['source'])
    assert hashlib.sha256(source.read_bytes()).hexdigest() == meta['source_sha256'], 'matrix_rows.jsonl changed'
    runs = [r for l in source.read_text().splitlines()
            if (r := json.loads(l)).get('in_matrix') and r.get('matrix_role') == 'method']
    assert len(runs) == 18
    for r in runs:                                   # the (0.05, 0.05) cell is Table 3's certificate
        for _, f in FIELDS:
            assert r[f'g0505_{f}'] == r[f], (r['setting'], r['seed'], f)
    cells = []
    t = [T.HEADER, f'% Generated by make_alpha_delta_table.py; the table environment, caption and label are in {WRAPPED_IN}.']
    t += T.table_open()
    for pi, (panel, indices) in enumerate(T.PANELS):
        settings = [T.SETTINGS[i] for i in indices]
        t += [l.replace(r'\textbf{Method}', r'\textbf{Limits}') for l in T.panel_head(pi, panel, indices)]
        for g, a, d in GRID:
            vv = []
            for s in settings:
                rs = [r for r in runs if r['setting'] == s]
                assert len(rs) == len({r['seed'] for r in rs}) == 3
                test = [{k: r[f'{g}_{f}'] for k, f in FIELDS} for r in rs]
                limited = all(r[f'{g}_lim6c'] for r in rs)
                for key, _ in T.METRICS:
                    v = T.value(test, key)
                    if key in T.ERR_OF and all(x[T.ERR_OF[key]] is None for x in test):
                        v = '--'
                    if key == 'abstain' and limited:
                        v = v[:-1] + r'^{\dagger}$'
                    defined = [100 * x[key] for x in test if x[key] is not None]
                    vv.append(v)
                    cells.append(dict(table=NAME, alpha=float(a), delta=float(d), setting=s, metric=key, n=len(defined),
                                      seeds_limited=sum(bool(r[f'{g}_lim6c']) for r in rs),
                                      seeds_certified=sum(bool(r[f'{g}_c6c_pass']) for r in rs),
                                      mean=round(sum(defined) / len(defined), 6) if defined else None, tex=v))
            t.append(label(a, d) + ' & ' + ' & '.join(vv) + r' \\')
    t += T.table_close()
    T.assert_means_only(NAME, t)
    out = T.TABLES / f'{NAME}_body.tex'
    out.write_text('\n'.join(t) + '\n')
    (VALUES / f'table_{NAME}_values.json').write_text(json.dumps(dict(
        generated_by='scripts/make_alpha_delta_table.py',
        source_hashes={str(source): meta['source_sha256']}, cells=cells), indent=2) + '\n')
    where = ''
    if paper:
        shutil.copyfile(out, PAPER_TABLES / out.name)
        where = f' -> paper tables/{out.name}'
    print(f'{out.name}: {len(cells)} cells{where}')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    p.add_argument('--paper', action='store_true', help='copy the body into the paper clone tables/')
    main(p.parse_args().paper)
