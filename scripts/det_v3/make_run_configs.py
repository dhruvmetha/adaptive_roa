#!/usr/bin/env python
"""Write one Hydra config per det_v3 run: configs/adaptive_v2/experiment/det_v3/runs/<name>.yaml.

Reads scripts/det_v3/run_plan.json (the tracker's machine-readable plan; to-do rows
have a rank). Launch a run as `+experiment=det_v3/runs/<name>` with
scripts/run_adaptive.py. (det_v3 has no Part-X rows: Part-X is recertified offline.)

    make_run_configs.py [--plan scripts/det_v3/run_plan.json] [--check]

--check fails if a written config differs from what the plan gives.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "configs/adaptive_v2/experiment/det_v3/runs"

# setting -> (system config, initial_train_size, samples_per_epoch); 10 rounds, 11 epochs.
SETTINGS = {
    "q3d-lqr": ("quadrotor3d", 10000, 2000),
    "q3d-ppo": ("quadrotor3d_rl", 10000, 3000),
    "q2d-ppo": ("quadrotor2d", 2000, 1000),
    "cp-lqr": ("cartpole_pybullet", 500, 150),
    "cp-ppo": ("cartpole_ppo", 500, 150),
    "pen-lqr": ("pendulum", 50, 35),
}
# setting -> (|D_val|, |D_cal|): first rows of the fixed val/cal files (random order), Sumanth 2026-11-07.
SPLITS = {"q3d-lqr": (1000, 5000), "q3d-ppo": (5000, 10000), "q2d-ppo": (1500, 5000),
          "cp-lqr": (500, 1000), "cp-ppo": (500, 2000), "pen-lqr": (500, 1000)}
MODELS = {"FM": "fm_det", "MLP classifier": "det_mlp_clf", "BNN classifier": "det_bnn_clf",
          "MLP final-state": "det_mlp_reg", "BNN final-state": "det_bnn_reg"}


def threshold_group(change: str | None) -> str:
    return "j_sel"                                  # A9 (hysteresis) is not in det_v3


def ablation(change: str | None) -> tuple[str, dict]:
    """(acquisition group, overrides) for a run's Change column; None is the main q_A arm."""
    if change is None:
        return "q_a", {}
    if change == "plain top-k (tie_tol = 0)":                     # A10
        return "q_a", {"acquisition": {"tie_tol": 0.0}}
    if change == "proportional sampling":                          # A10
        return "q_a", {"acquisition": {"selection": "proportional"}}
    if change in ("initial batch x 0.5", "initial batch x 2"):    # A11: budget set in render()
        return "q_a", {}
    if change == "U_H instead of q_A":
        return "u_h", {}
    m = re.fullmatch(r"(J_sel|J_ver), w = ([0-9.]+)", change)
    if m:
        return "q_a", {"threshold": {"objective": m.group(1).lower(), "w": float(m.group(2))}}
    m = re.fullmatch(r"d2_ratio = ([0-9.]+)", change)
    if m:
        return "q_a", {"acquisition": {"d2_ratio": float(m.group(1))}}
    raise ValueError(f"unknown ablation change {change!r}")


def _yaml(d: dict, indent: int = 0) -> list[str]:
    lines = []
    for k, v in d.items():
        if isinstance(v, dict):
            lines.append(" " * indent + f"{k}:")
            lines += _yaml(v, indent + 2)
        else:
            lines.append(" " * indent + f"{k}: {str(v).lower() if isinstance(v, bool) else v}")
    return lines


def initial_budget(run: dict) -> tuple[int, int]:
    """(initial_train_size, samples_per_epoch). A11 halves or doubles the initial uniform batch and moves
    the difference into the 10 acquisition rounds, so the final training-set size is unchanged
    (pendulum's half batch rounds 37.5 up to 38 per round: 405 trajectories instead of 400)."""
    _, n0, k = SETTINGS[run["setting"]]
    change = run.get("change")
    if change == "initial batch x 0.5":
        return n0 // 2, int(-(-(k * 10 + n0 - n0 // 2) // 10))
    if change == "initial batch x 2":
        return 2 * n0, (k * 10 + n0 - 2 * n0) // 10
    return n0, k


def render(run: dict) -> str:
    system = SETTINGS[run["setting"]][0]
    n0, per_round = initial_budget(run)
    n_val, n_cal = SPLITS[run["setting"]]
    head = (f"# @package _global_\n"
            f"# det_v3 run {run['id']}: {run['setting']}, {run['model']}, "
            f"{run.get('change') or run['arm']} (rank {run['rank']}, owner {run['owner']}).\n"
            f"# Generated by scripts/det_v3/make_run_configs.py from scripts/det_v3/run_plan.json.\n")
    body: dict = {"det_v3_run": run["name"], "initial_train_size": n0, "samples_per_epoch": per_round,
                  "n_epochs": 11, "data_source": {"val_set_max_rows": n_val, "cal_set_max_rows": n_cal}}
    if run["model"] == "Part-X":
        raise ValueError("det_v3 has no Part-X runs (Part-X is recertified offline)")
    else:
        if run.get("arm") == "uniform":
            acq, extra = "q_a", {"acquisition": {"d2_ratio": 0.0}}
        else:
            acq, extra = ablation(run.get("change"))
            extra.setdefault("acquisition", {}).setdefault("d2_ratio", 1.0)
        defaults = ["/experiment/det_v3", f"override /system: {system}",
                    f"override /predictor: {MODELS[run['model']]}",
                    f"override /acquisition: {acq}", f"override /threshold: {threshold_group(run.get('change'))}",
                    "_self_"]
        body.update(extra)
        if run["model"] == "FM":
            # Bias-free speedup: the in-training endpoint MAE ODE pass feeds only
            # validation_errors.txt.
            body["predictor"] = {"flow_matching": {"mae_val_frequency": 1000000}}
        elif run["model"] in ("MLP final-state", "BNN final-state"):
            # Bias-free speedup: the deterministic MLP body once per batch, not once per draw.
            body["predictor"] = {"final_state": {"reuse_body_features": True}}
    body["output_dir"] = f"${{exp_dir}}/det_v3/{run['setting']}/{run['name']}_s${{seed}}"
    return head + "defaults:\n" + "".join(f"  - {d}\n" for d in defaults) + "\n" + "\n".join(_yaml(body)) + "\n"


def todo_runs(plan: dict) -> list[dict]:
    runs = [r for r in plan["main"] + plan["abl"] if r.get("rank") is not None]
    return sorted(runs, key=lambda r: r["rank"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", type=Path, default=ROOT / "scripts/det_v3/run_plan.json")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    runs = todo_runs(json.loads(a.plan.read_text()))
    OUT.mkdir(parents=True, exist_ok=True)
    bad = []
    for r in runs:
        path, text = OUT / f"{r['name']}.yaml", render(r)
        if a.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    if bad:
        sys.exit(f"{len(bad)} configs differ from the plan: {bad[:5]}")
    print(f"{len(runs)} run configs {'match the plan' if a.check else 'written'} in {OUT}")


if __name__ == "__main__":
    main()
