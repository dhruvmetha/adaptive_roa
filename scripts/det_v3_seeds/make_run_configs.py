#!/usr/bin/env python
"""Write one Hydra config per det_v3_seeds run: configs/adaptive_v2/experiment/det_v3_seeds/runs/<name>.yaml.

Each config composes the det_v3 run config it repeats and sets the seed, the output_dir
(under ${exp_dir}/det_v3_seeds) and the run label det_v3_run, plus the row's one change: an
acquisition group override (u_tau or u_h) and/or top-level values (the A11 schedule,
acquisition_mc_samples). Rows past rank 180 also take the plan's prediction_store override
(make_plan.NEW_ROW_STORE: endpoint dumps). D_val, D_cal and the test set do not move with the seed
(data_source.SPLIT_SUBSET_SEED). Launch a run as `+experiment=det_v3_seeds/runs/<name>` with
scripts/run_adaptive.py.

    make_run_configs.py [--plan scripts/det_v3_seeds/run_plan.json] [--check]

--check fails if a written config differs from what the plan gives.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "configs/adaptive_v2/experiment/det_v3_seeds/runs"


def render(run: dict) -> str:
    acq, extra = run.get("acquisition"), run.get("set", {})
    # What this config overrides in its det_v3 base: the acquisition group, and/or the values in "set"
    # (an A11 schedule or K, which the row's change names).
    parts = ([f"acquisition {acq}"] if acq else []) + ([run["change"]] if extra else [])
    change = f"# Change from det_v3 {run['base_id']}: {'; '.join(parts)}.\n" if parts else ""
    return (f"# @package _global_\n"
            f"# det_v3_seeds run {run['id']}: det_v3 {run['base_id']} ({run['base_name']}) at seed {run['seed']} "
            f"(rank {run['rank']}, owner {run['owner']}).\n"
            f"{change}"
            f"# Generated by scripts/det_v3_seeds/make_run_configs.py from scripts/det_v3_seeds/run_plan.json.\n"
            f"defaults:\n"
            f"  - /experiment/det_v3/runs/{run['base_name']}\n"
            + (f"  - override /acquisition: {acq}\n" if acq else "")
            + f"  - _self_\n"
            f"\n"
            f"det_v3_run: {run['name']}\n"
            + "".join(f"{k}: {v}\n" for k, v in extra.items())
            + ("prediction_store:\n" + "".join(f"  {k}: {json.dumps(v)}\n" for k, v in run["store"].items())
               if run.get("store") else "")
            + f"seed: {run['seed']}\n"
            f"output_dir: ${{exp_dir}}/det_v3_seeds/{run['setting']}/{run['name']}_s${{seed}}\n")


def all_runs(plan: dict) -> list[dict]:
    return sorted((r for rows in plan.values() for r in rows), key=lambda r: r["rank"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", type=Path, default=ROOT / "scripts/det_v3_seeds/run_plan.json")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    runs = all_runs(json.loads(a.plan.read_text()))
    OUT.mkdir(parents=True, exist_ok=True)
    bad = []
    for r in runs:
        path, text = OUT / f"{r['name']}.yaml", render(r)
        if a.check:
            if not path.exists() or path.read_text() != text:
                bad.append(path.name)
        else:
            path.write_text(text)
    extra = sorted({p.stem for p in OUT.glob("*.yaml")} - {r["name"] for r in runs})
    if extra:
        bad += [f"{n}.yaml (not in the plan)" for n in extra]
    if bad:
        sys.exit(f"{len(bad)} configs differ from the plan: {bad[:5]}")
    print(f"{len(runs)} run configs {'match the plan' if a.check else 'written'} in {OUT}")


if __name__ == "__main__":
    main()
