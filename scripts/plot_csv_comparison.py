def load_gt_csv(slice_name: str):
    """Load ground truth CSV. Returns (gt_labels_flat, n0, n1)."""
    sl = SLICES[slice_name]
    df = pd.read_csv(sl["gt_csv"])
    ax0, ax1 = sl["gt_ax0_col"], sl["gt_ax1_col"]
    df = df.sort_values([ax0, ax1]).reset_index(drop=True)
    n0 = df[ax0].nunique()
    n1 = df[ax1].nunique()
    labels = df["label"].values.astype(np.int8)
    print(f"  GT {sl['gt_csv'].name}: {n0}x{n1}={len(df)} pts, "
          f"success={np.sum(labels==1)} ({100*np.mean(labels==1):.1f}%)")
    return labels, n0, n1


def load_deepreach_csv(slice_name: str):
    """Load DeepReach CSV. Returns (pred_labels_flat, values_flat, n0, n1).

    pred_labels: {-1, 0, 1} = {uncertain, failure, success}
    """
    sl = SLICES[slice_name]
    df = pd.read_csv(sl["dr_csv"])
    ax0, ax1 = sl["dr_ax0_col"], sl["dr_ax1_col"]
    df = df.sort_values([ax0, ax1]).reset_index(drop=True)
    n0 = df[ax0].nunique()
    n1 = df[ax1].nunique()
    labels = df["pred_label"].values.astype(np.int8)
    values = df["value"].values.astype(np.float32)
    n_safe = np.sum(labels == 1)
    n_fail = np.sum(labels == 0)
    n_unc = np.sum(labels == -1)
    total = len(labels)
    print(f"  DeepReach {sl['dr_csv'].name}: {n0}x{n1}={total} pts, "
          f"success={n_safe} ({100*n_safe/total:.1f}%), "
          f"fail={n_fail} ({100*n_fail/total:.1f}%), "
          f"uncertain={n_unc} ({100*n_unc/total:.1f}%)")
    return labels, values, n0, n1


def load_olympics_cache(slice_name: str, epoch: int):
    """Load Olympics classifier cache. Returns dict[method_name] -> {pred_labels, ...} or None."""
    cf = OLYMPICS_CACHE_DIR / f"qualitative_cartpole_{slice_name}_cache.npz"
    if not cf.exists():
        print(f"  Olympics cache not found: {cf}")
        return None

    data = np.load(str(cf), allow_pickle=False)
    methods = {}
    for cache_key, display_name in _CACHE_KEY_MAP.items():
        prefix = f"{cache_key}_epoch{epoch}"
        key = f"{prefix}_pred"
        if key not in data:
            print(f"  Warning: {cache_key} epoch {epoch} not in cache, skipping")
            continue
        methods[display_name] = {
            "pred_labels": data[f"{prefix}_pred"],
            "p_success": data[f"{prefix}_psuc"],
            "lambda_star": float(data[f"{prefix}_lam"]),
            "delta_star": float(data[f"{prefix}_delta"]),
        }
    if not methods:
        return None
    print(f"  Olympics cache loaded: {list(methods.keys())}")
    return methods


