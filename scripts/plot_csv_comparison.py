def plot_bare_singles(all_data: dict, epoch: int):
    """Save individual bare heatmaps for each method/slice."""
    cmap, norm = _discrete_cmap()

    for slice_name, d in all_data.items():
        sl = SLICES[slice_name]
        extent = [*sl["sweep_ranges"][0], *sl["sweep_ranges"][1]]
        n0, n1 = d["n0"], d["n1"]

        # GT
        _save_bare(d["gt_heatmap"], extent, cmap,
                   f"csv_{slice_name}_ground_truth", norm=norm)

        # DeepReach
        if "deepreach_heatmap" in d:
            _save_bare(d["deepreach_heatmap"], extent, cmap,
                       f"csv_{slice_name}_deepreach", norm=norm)

        # Olympics methods
        if "olympics" in d:
            for method_name, mdata in d["olympics"].items():
                safe = method_name.replace(" ", "_").replace("(", "").replace(")", "")
                hm = _pred_to_heatmap(mdata["pred_labels"], n0, n1)
                _save_bare(hm, extent, cmap,
                           f"csv_{slice_name}_{safe}_ep{epoch}", norm=norm)


