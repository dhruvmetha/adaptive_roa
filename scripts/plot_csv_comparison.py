def _build_method_columns(all_data):
    """Build ordered list of (label, heatmap_getter) for available methods."""
    first = next(iter(all_data.values()))
    cols = []

    # Olympics methods (if available)
    if "olympics" in first:
        for method_name in first["olympics"]:
            cols.append({
                "label": method_name,
                "get_heatmap": lambda d, n0, n1, m=method_name: _pred_to_heatmap(
                    d["olympics"][m]["pred_labels"], n0, n1),
                "get_labels": lambda d, m=method_name: d["olympics"][m]["pred_labels"],
                "failure_value": 0,
            })

    # DeepReach
    if "deepreach_heatmap" in first:
        cols.append({
            "label": "DeepReach",
            "get_heatmap": lambda d, n0, n1: d["deepreach_heatmap"],
            "get_labels": lambda d: d["deepreach_labels"],
            "failure_value": 0,  # DeepReach pred_label: 0=failure, 1=success, -1=uncertain
        })

    return cols


def plot_combined_horizontal(all_data: dict, epoch: int):
    """Horizontal layout: rows=slices, cols=(GT + methods)."""
    slice_names = list(all_data.keys())
    method_cols = _build_method_columns(all_data)
    col_labels = ["Ground Truth"] + [c["label"] for c in method_cols]
    n_rows = len(slice_names)
    n_cols = len(col_labels)

    cmap, norm = _discrete_cmap()
    label_fs = 13
    tick_fs = 12

    fig, axes = plt.subplots(
        n_rows, n_cols,
        figsize=(3.5 * n_cols, 3.0 * n_rows),
        squeeze=False,
        constrained_layout=True,
    )

    for row, slice_name in enumerate(slice_names):
        sl = SLICES[slice_name]
        d = all_data[slice_name]
        extent = [*sl["sweep_ranges"][0], *sl["sweep_ranges"][1]]
        n0, n1 = d["n0"], d["n1"]

        # GT column
        ax = axes[row, 0]
        ax.imshow(d["gt_heatmap"], origin="lower", aspect="auto",
                  cmap=cmap, norm=norm, extent=extent, interpolation="nearest")
        ax.set_xlabel(sl["xlabel"], fontsize=label_fs, fontweight="bold")
        ax.set_ylabel(sl["ylabel"], fontsize=label_fs, fontweight="bold")
        _style_ax(ax, sl, fontsize=tick_fs)

        # Method columns
        for col, mc in enumerate(method_cols, start=1):
            ax = axes[row, col]
            hm = mc["get_heatmap"](d, n0, n1)
            ax.imshow(hm, origin="lower", aspect="auto",
                      cmap=cmap, norm=norm, extent=extent, interpolation="nearest")
            ax.set_xlabel(sl["xlabel"], fontsize=label_fs, fontweight="bold")
            ax.set_ylabel(sl["ylabel"], fontsize=label_fs, fontweight="bold")
            _style_ax(ax, sl, fontsize=tick_fs)

    # Column titles
    for col, label in enumerate(col_labels):
        axes[0, col].set_title(label, fontsize=14, fontweight="bold")

    # Legend
    from matplotlib.patches import Patch
    legend_patches = [
        Patch(facecolor="#1a9850", label="Success"),
        Patch(facecolor="#fee08b", label="Uncertain"),
        Patch(facecolor="#d73027", label="Failure"),
    ]
    fig.legend(
        handles=legend_patches, loc="lower center",
        ncol=3, fontsize=12, frameon=False, prop={"weight": "bold"},
        bbox_to_anchor=(0.5, -0.04),
    )

    _save_fig(fig, f"csv_comparison_horiz_ep{epoch}")
    plt.close(fig)


