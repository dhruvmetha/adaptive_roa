def main():
    parser = argparse.ArgumentParser(
        description="Combined CartPole comparison from CSV files"
    )
    parser.add_argument("--epoch", type=int, default=DEFAULT_EPOCH,
                        help="Olympics epoch (default: 15)")
    parser.add_argument("--slice", default="theta_thetadot",
                        choices=list(SLICES.keys()))
    parser.add_argument("--all_slices", action="store_true",
                        help="Use both slices")
    parser.add_argument("--no_olympics", action="store_true",
                        help="Skip Olympics classifier (no cache needed)")
    parser.add_argument("--no_errors", action="store_true",
                        help="Skip FP/FN error analysis plots")
    args = parser.parse_args()

    slice_names = list(SLICES.keys()) if args.all_slices else [args.slice]

    # ── Load all data ─────────────────────────────────────────────────────
    all_data = {}

    for slice_name in slice_names:
        print(f"\n{'='*60}")
        print(f"Slice: {slice_name}")
        print(f"{'='*60}")

        # Ground truth
        gt_labels, n0, n1 = load_gt_csv(slice_name)
        gt_heatmap = _gt_to_heatmap(gt_labels, n0, n1)

        entry = {
            "gt_heatmap": gt_heatmap,
            "gt_labels": gt_labels,
            "n0": n0, "n1": n1,
        }

        # DeepReach
        dr_labels, dr_values, dn0, dn1 = load_deepreach_csv(slice_name)
        assert dn0 == n0 and dn1 == n1, (
            f"Grid mismatch: GT {n0}x{n1} vs DeepReach {dn0}x{dn1}")
        entry["deepreach_heatmap"] = _3class_to_heatmap(dr_labels, n0, n1)
        entry["deepreach_labels"] = dr_labels

        # Olympics (optional)
        if not args.no_olympics:
            olympics = load_olympics_cache(slice_name, args.epoch)
            if olympics:
                entry["olympics"] = olympics

        all_data[slice_name] = entry

    # ── Generate plots ────────────────────────────────────────────────────
    print("\nGenerating individual bare heatmaps...")
    plot_bare_singles(all_data, args.epoch)

    print("\nGenerating combined horizontal comparison...")
    plot_combined_horizontal(all_data, args.epoch)

    print("\nGenerating combined vertical comparison...")
    plot_combined_vertical(all_data, args.epoch)

    if not args.no_errors:
        print("\nGenerating error analysis plots...")
        plot_error_horizontal(all_data, args.epoch)
        plot_error_vertical(all_data, args.epoch)

    print("\nDone.")


if __name__ == "__main__":
    main()
